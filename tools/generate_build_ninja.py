#!/usr/bin/env python3
"""Generate the native ARM64 Ninja graph from the checked-out source tree.

Game AOT assembly and guest images remain local inputs and are never copied or
generated by this script. Object names are stable so an incremental build can
reuse the existing objects.
"""

from __future__ import annotations

import argparse
import os
import re
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
RECOMPILER = Path("gpu/shadps4-recompiler")


def object_for(source: Path, cxx23: bool = False) -> Path:
    if cxx23:
        return Path("build/gcn") / (str(source).replace("/", "_").removesuffix(".cpp") + ".o")
    return source.with_suffix(".o")


def unique(paths: list[Path], what: str, *, sort: bool = False) -> list[Path]:
    result = sorted(paths, key=lambda path: path.as_posix()) if sort else list(paths)
    seen: set[Path] = set()
    for path in result:
        if path in seen:
            raise ValueError(f"duplicate {what} in generated build graph: {path}")
        seen.add(path)
    return result


def collect_sources(root: Path) -> tuple[list[Path], list[Path]]:
    required = [
        Path("main.c"), Path("trampoline_arm64.s"), Path("dispatch.c"),
        Path("guest_modules.c"), Path("guest_modules_synth.s"),
        Path("gpu/gow3gpu_bridge.cpp"),
        Path("runtime/modules/libSceGnmDriver/ps4_gcn_translate.cpp"),
    ]
    missing = [path.as_posix() for path in required if not (root / path).is_file()]
    if missing:
        raise FileNotFoundError("missing required project sources: " + ", ".join(missing))

    local_sources = [Path("main.c"), Path("trampoline_arm64.s")]
    for assembly in sorted(root.glob("code_*.s")):
        if not re.fullmatch(r"code_\d+\.s", assembly.name):
            continue  # code_NNN.opt.s: the peephole output of code_NNN.s
        local_sources.append(assembly.relative_to(root))
        registration = assembly.with_name(assembly.stem + "_reg.c")
        if registration.is_file():
            local_sources.append(registration.relative_to(root))
    local_sources += [Path("dispatch.c"), Path("guest_modules.c"), Path("guest_modules_synth.s")]
    local_sources += [path.relative_to(root) for path in sorted(
        (root / "3rdparty/libatrac9/C/src").glob("*.c"))]
    runtime_sources = [path.relative_to(root) for path in sorted((root / "runtime").rglob("*"))
                       if path.is_file() and path.suffix in {".c", ".m", ".mm", ".cpp"}]
    for path in runtime_sources:
        local_sources.append(path)
        if path == Path("runtime/modules/libSceGnmDriver/ps4_gnmdriver.c"):
            local_sources.append(Path("gpu/gow3gpu_bridge.cpp"))
    local_sources = unique(local_sources, "application source")

    gcn_sources = list((root / RECOMPILER / "src/shader_recompiler").rglob("*.cpp"))
    gcn_sources = [path.relative_to(root) for path in gcn_sources
                   if path.name != "flatten_extended_userdata_pass.cpp"]
    gcn_sources += [path.relative_to(root) for path in (root / RECOMPILER / "sirit/src").rglob("*.cpp")]
    gcn_sources += [
        RECOMPILER / "src/video_core/amdgpu/pixel_format.cpp",
        RECOMPILER / "port/flatten_userdata_arm64.cpp",
    ]
    gcn_sources = unique(gcn_sources, "recompiler source", sort=True)
    missing_gcn = [path.as_posix() for path in gcn_sources if not (root / path).is_file()]
    if missing_gcn:
        raise FileNotFoundError("missing recompiler sources: " + ", ".join(missing_gcn))
    return local_sources, gcn_sources


def render(root: Path) -> str:
    local_sources, gcn_sources = collect_sources(root)
    driver_translate = Path("runtime/modules/libSceGnmDriver/ps4_gcn_translate.cpp")
    app_sources = [path for path in local_sources if path != driver_translate]
    cpp23_sources = [*gcn_sources, driver_translate]

    outputs: dict[Path, Path] = {}
    for source in [*app_sources, *cpp23_sources]:
        cxx23 = source in cpp23_sources
        output = object_for(source, cxx23)
        prior = outputs.get(output)
        if prior is not None:
            raise ValueError(f"object collision: {prior} and {source} both produce {output}")
        outputs[output] = source

    cflags = (
        "-target arm64-apple-darwin -mcpu=apple-m2 -DRECOMP_ARM64_ASM=1 -O2 "
        "-ffp-contract=off -fvisibility=hidden -Wno-parentheses-equality -I. -Igpu "
        "-I3rdparty/libatrac9/C/src -I3rdparty/minimp3  -I3rdparty/spirv-cross "
        "-I/opt/homebrew/include -I/opt/homebrew/include/spirv_cross "
        "-I/opt/homebrew/include/spirv-cross -I/opt/homebrew/opt/freetype/include/freetype2 "
        "-I/opt/homebrew/include/freetype2 -Iruntime/core -Iruntime/kernel "
        "-Iruntime/kernel/aio -Iruntime/kernel/equeue -Iruntime/kernel/memory "
        "-Iruntime/kernel/sync -Iruntime/kernel/syscalls -Iruntime/kernel/threading "
        "-Iruntime/kernel/vfs -Iruntime/modules -Iruntime/modules/libSceAjm "
        "-Iruntime/modules/libSceAppContent -Iruntime/modules/libSceAudioIn "
        "-Iruntime/modules/libSceAudioOut -Iruntime/modules/libSceAudiodec "
        "-Iruntime/modules/libSceCamera -Iruntime/modules/libSceErrorDialog "
        "-Iruntime/modules/libSceFiber -Iruntime/modules/libSceFreeType "
        "-Iruntime/modules/libSceGnmDriver -Iruntime/modules/libSceHmd "
        "-Iruntime/modules/libSceHttp -Iruntime/modules/libSceIme "
        "-Iruntime/modules/libSceImeDialog -Iruntime/modules/libSceInvitationDialog "
        "-Iruntime/modules/libSceJpegDec "
        "-Iruntime/modules/libSceJpegEnc -Iruntime/modules/libSceJson2 "
        "-Iruntime/modules/libSceMouse -Iruntime/modules/libSceMove "
        "-Iruntime/modules/libSceMsgDialog -Iruntime/modules/libSceNet "
        "-Iruntime/modules/libSceNetCtl -Iruntime/modules/libSceNoopStubs "
        "-Iruntime/modules/libSceNp -Iruntime/modules/libSceNpProfileDialog "
        "-Iruntime/modules/libSceNpSns -Iruntime/modules/libSceNpTrophy "
        "-Iruntime/modules/libSceNpUtility -Iruntime/modules/libScePad "
        "-Iruntime/modules/libScePlayGo -Iruntime/modules/libScePngDec "
        "-Iruntime/modules/libScePosix -Iruntime/modules/libSceRandom "
        "-Iruntime/modules/libSceRemoteplay -Iruntime/modules/libSceRtc "
        "-Iruntime/modules/libSceSaveData -Iruntime/modules/libSceSaveDataDialog "
        "-Iruntime/modules/libSceScreenShot -Iruntime/modules/libSceSharePlay "
        "-Iruntime/modules/libSceSigninDialog -Iruntime/modules/libSceSocialScreen "
        "-Iruntime/modules/libSceSsl -Iruntime/modules/libSceSystemService "
        "-Iruntime/modules/libSceUserService -Iruntime/modules/libSceVideoOut "
        "-Iruntime/modules/libSceVideoRecording -Iruntime/modules/libSceVoice "
        "-Iruntime/modules/libSceVoiceQoS -Iruntime/modules/libSceVrTracker "
        "-Iruntime/modules/libSceWebBrowserDialog -Iruntime/modules/libkernel"
    )
    recomp_flags = (
        "-Igpu/shadps4-recompiler/shims -Igpu/shadps4-recompiler "
        "-Igpu/shadps4-recompiler/src -Igpu/shadps4-recompiler/sirit/include "
        "-Igpu/shadps4-recompiler/sirit/src -Igpu/shadps4-recompiler/SPIRV-Headers "
        "-Wno-unused-parameter -Wno-unused-variable -Wno-unused-function "
        "-Wno-sign-compare -Wno-missing-field-initializers -Wno-deprecated-declarations"
    )
    ldflags = (
        "-target arm64-apple-darwin -mcpu=apple-m2 -Wl,-dead_strip -Wl,-x "
        "-framework Metal -framework Cocoa -framework QuartzCore "
        "-framework GameController -framework AudioToolbox -framework ImageIO "
        "-framework MetalFX -framework VideoToolbox -framework CoreMedia "
        "-framework CoreVideo -lz -lpthread -lm -L/opt/homebrew/lib "
        "-Wl,-rpath,/opt/homebrew/opt/ffmpeg/lib "
        "-L/opt/homebrew/opt/freetype/lib -lfreetype -lspirv-cross-msl "
        "-lspirv-cross-core -lspirv-cross-glsl -lfmt -lavcodec -lswscale "
        "-lavutil -lc++"
    )

    lines = [
        "# Generated by tools/generate_build_ninja.py; do not edit by hand.",
        "ninja_required_version = 1.5",
        "",
        f"cflags = {cflags}",
        f"recomp_flags = {recomp_flags}",
        "",
        "rule regenerate_build_ninja",
        "  command = python3 tools/generate_build_ninja.py --root . --output build.ninja",
        "  generator = 1",
        "  restat = 1",
        "",
        "build build.ninja: regenerate_build_ninja tools/generate_build_ninja.py",
        "",
        "rule compile_c",
        "  command = clang -MD -MF $out.d $cflags -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CC $in",
        "",
        "rule compile_s",
        "  command = clang -MD -MF $out.d $cflags -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = AS $in",
        "",
        "rule compile_m",
        "  command = clang -MD -MF $out.d $cflags -fobjc-arc -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = OBJC $in",
        "",
        "rule compile_mm",
        "  command = clang++ -MD -MF $out.d $cflags -fobjc-arc -std=c++17 -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = OBJCXX $in",
        "",
        "rule compile_cpp",
        "  command = clang++ -MD -MF $out.d $cflags -std=c++17 -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CXX $in",
        "",
        "rule compile_cpp23",
        "  command = clang++ -MD -MF $out.d $recomp_flags $cflags -std=c++23 -c $in -o $out",
        "  depfile = $out.d",
        "  deps = gcc",
        "  description = CXX23 $in",
        "",
        "rule peephole_guest",
        "  command = python3 tools/peephole_guest_code.py $peephole_flags $in $out > /dev/null",
        "  description = PEEPHOLE $in",
        "",
        "rule archive_gcn",
        "  command = libtool -static -o $out $in",
        "  description = AR $out",
        "",
        f"ldflags = {ldflags}",
        "",
        "rule link_bin",
        "  command = clang $in $ldflags -o $out",
        "  description = LINK $out",
        "",
    ]

    rule_for = {".c": "compile_c", ".s": "compile_s", ".m": "compile_m",
                ".mm": "compile_mm", ".cpp": "compile_cpp"}
    # Recompiled guest code goes through exact peephole rewrites (tools/peephole_guest_code.py)
    # before it is assembled; GOW3_GUEST_PEEPHOLE=0 when generating assembles it unchanged. Every
    # guest access has an inline 16-byte-crossing check only when GOW3_GUEST_TSO_CHECKS=1; by default it
    # is dropped outside the functions in tools/tso_crossing_sites.txt: +2-3 FPS on the profiled Mount
    # Olympus save, but a crossing in a stage not yet profiled costs a ~2 us fault (up to 200,000/s seen).
    peephole = os.environ.get("GOW3_GUEST_PEEPHOLE", "1") != "0"
    # Operation Spartan (Argon) fix #1: checks are dropped by default, outside the functions listed in
    # tools/tso_crossing_sites.txt; a crossing elsewhere is caught by the SIGBUS fixup in
    # runtime/core/tso_crossing.c (~2 us each). GOW3_GUEST_TSO_CHECKS=1 when generating keeps them all.
    keep_checks = os.environ.get("GOW3_GUEST_TSO_CHECKS", "0") != "0"
    lines.append(f"peephole_flags = {'--keep-tso-checks' if keep_checks else ''}")
    for source in app_sources:
        if peephole and re.fullmatch(r"code_\d+\.s", source.as_posix()):
            optimized = source.with_suffix(".opt.s").as_posix()
            lines.append(f"build {optimized}: peephole_guest {source.as_posix()} | tools/peephole_guest_code.py tools/tso_crossing_sites.txt")
            lines.append(f"build {object_for(source).as_posix()}: compile_s {optimized}")
            continue
        lines.append(f"build {object_for(source).as_posix()}: {rule_for[source.suffix]} {source.as_posix()}")
    for source in cpp23_sources:
        lines.append(f"build {object_for(source, cxx23=True).as_posix()}: compile_cpp23 {source.as_posix()}")

    archive = Path("build/gcn/libgcn_recompiler.a")
    gcn_objects = [object_for(path, cxx23=True).as_posix() for path in gcn_sources]
    lines += ["", f"build {archive.as_posix()}: archive_gcn {' '.join(gcn_objects)}", ""]
    app_objects = [object_for(path).as_posix() for path in app_sources]
    app_objects += [archive.as_posix(), object_for(driver_translate, cxx23=True).as_posix()]
    lines += [f"build ps4_app: link_bin {' '.join(app_objects)}", "default ps4_app", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    output = (args.output or root / "build.ninja").resolve()
    try:
        content = render(root)
    except (FileNotFoundError, ValueError) as exc:
        print(f"build generation failed: {exc}", file=sys.stderr)
        return 2
    output.parent.mkdir(parents=True, exist_ok=True)
    previous = output.read_text(encoding="utf-8") if output.exists() else None
    if previous != content:
        with output.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
        print(f"generated {output}")
    else:
        print(f"unchanged {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
