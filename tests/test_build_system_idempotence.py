#!/usr/bin/env python3
"""
Test suite verifying Ninja Build-System Idempotence and Integrity:
1. Validates that no target in build.ninja is generated by multiple rules.
2. Validates that gpu/gow3gpu_bridge.o is generated by exactly one rule.
3. Validates that gpu/gow3gpu_bridge.o is linked into ps4_app exactly once.
4. Validates that running patch_build_ninja.py multiple times is 100% idempotent.
5. Runs ninja dry-run (-n) to ensure Ninja parses the entire build graph with 0 errors.
"""

import os
import sys
import subprocess

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NINJA_FILE = os.path.join(BASE_DIR, "build.ninja")
PATCH_TOOL = os.path.join(BASE_DIR, "tools", "patch_build_ninja.py")

def test_no_duplicate_outputs():
    print("[1] Inspecting build.ninja for duplicate output targets...")
    with open(NINJA_FILE, "r", encoding="utf-8") as f:
        lines = f.readlines()

    generated_targets = {}
    for line_num, line in enumerate(lines, 1):
        line = line.strip()
        if line.startswith("build ") and ":" in line:
            # build target1 target2 ... : rule ...
            targets_part = line[len("build "):line.find(":")].strip()
            targets = targets_part.split()
            for t in targets:
                if t not in generated_targets:
                    generated_targets[t] = []
                generated_targets[t].append((line_num, line))

    duplicates = {t: occurrences for t, occurrences in generated_targets.items() if len(occurrences) > 1}
    assert len(duplicates) == 0, f"Found targets generated by multiple rules in build.ninja:\n{duplicates}"
    print(f"    [+] Verified {len(generated_targets)} distinct output targets; zero duplicates found.")

def test_bridge_rule_and_link():
    print("[2] Verifying gpu/gow3gpu_bridge.o compilation rule and link dependency...")
    with open(NINJA_FILE, "r", encoding="utf-8") as f:
        content = f.read()

    lines = content.splitlines()

    # Find rules generating gpu/gow3gpu_bridge.o
    bridge_rules = [l for l in lines if l.startswith("build gpu/gow3gpu_bridge.o:")]
    assert len(bridge_rules) == 1, f"Expected exactly 1 rule generating gpu/gow3gpu_bridge.o, found {len(bridge_rules)}: {bridge_rules}"
    assert "compile_cpp" in bridge_rules[0], f"Rule must use compile_cpp, got: {bridge_rules[0]}"
    print(f"    [+] Exactly one rule generates gpu/gow3gpu_bridge.o: {bridge_rules[0]}")

    # Check ps4_gnmdriver.o rule doesn't touch gow3gpu_bridge.o
    gnmdriver_rules = [l for l in lines if "runtime/modules/libSceGnmDriver/ps4_gnmdriver.o" in l and l.startswith("build ")]
    for r in gnmdriver_rules:
        if ":" in r and r.find(":") > r.find("ps4_gnmdriver.o"):
            targets = r[len("build "):r.find(":")].split()
            assert "gpu/gow3gpu_bridge.o" not in targets, f"ps4_gnmdriver rule must not list gow3gpu_bridge.o as output! Line: {r}"
    print("    [+] ps4_gnmdriver compilation rule cleanly separated.")

    # Check link line
    link_line = [l for l in lines if l.startswith("build ps4_app: link_bin")][0]
    tokens = link_line.split()
    bridge_count = tokens.count("gpu/gow3gpu_bridge.o")
    assert bridge_count == 1, f"Expected gpu/gow3gpu_bridge.o to be linked exactly once, found {bridge_count}"
    print("    [+] gpu/gow3gpu_bridge.o is linked into ps4_app exactly once.")

def test_patcher_idempotence():
    print("[3] Verifying patch_build_ninja.py idempotency...")
    # Read initial state
    with open(NINJA_FILE, "rb") as f:
        before = f.read()

    # Run patcher
    res = subprocess.run([sys.executable, PATCH_TOOL, NINJA_FILE], capture_output=True, text=True)
    assert res.returncode == 0, f"patch_build_ninja.py failed: {res.stderr}"

    with open(NINJA_FILE, "rb") as f:
        after = f.read()

    assert before == after, "patch_build_ninja.py modified an already-clean build.ninja! It must be idempotent."
    print("    [+] patch_build_ninja.py is 100% idempotent (bit-for-bit identical after execution).")

def test_ninja_parse():
    print("[4] Executing Ninja dry-run (-n) to verify clean parser execution...")
    # Find ninja executable
    ninja_cmd = None
    try:
        import ninja
        ninja_exe = os.path.join(ninja.BIN_DIR, "ninja.exe" if os.name == "nt" else "ninja")
        if os.path.exists(ninja_exe):
            ninja_cmd = ninja_exe
    except ImportError:
        pass

    if not ninja_cmd:
        import shutil
        ninja_cmd = shutil.which("ninja")

    if ninja_cmd:
        res = subprocess.run([ninja_cmd, "-C", BASE_DIR, "-n"], capture_output=True, text=True)
        assert res.returncode == 0, f"Ninja dry-run failed with exit code {res.returncode}:\n{res.stdout}\n{res.stderr}"
        assert "multiple rules generate" not in res.stderr
        print(f"    [+] Ninja dry-run succeeded cleanly with 0 errors using {ninja_cmd}!")
    else:
        print("    [*] Notice: ninja binary not in path, skipped live binary execution.")

if __name__ == "__main__":
    print("=" * 60)
    print("  TEST: Ninja Build-System Idempotence & Target Integrity")
    print("=" * 60)
    test_no_duplicate_outputs()
    test_bridge_rule_and_link()
    test_patcher_idempotence()
    test_ninja_parse()
    print("=" * 60)
    print("  ALL BUILD SYSTEM TESTS PASSED (4/4)")
    print("=" * 60)
